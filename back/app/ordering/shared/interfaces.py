"""Replaceable persistence and payment contracts for Sprint 2."""

from dataclasses import dataclass
from decimal import Decimal
from typing import Protocol

from app.ordering.models import BrowseCategory, Cart, FoodOrder, MenuItem, PaymentEvent, Restaurant


class CatalogRepository(Protocol):
    def list_restaurants(
        self,
        category: str | None,
        search: str | None,
        limit: int,
        offset: int,
        kind: str | None = None,
        sort: str = "rating",
        free_delivery: bool = False,
        max_delivery_minutes: int | None = None,
    ) -> list[Restaurant]: ...
    def list_browse_categories(self) -> list[BrowseCategory]: ...
    def list_favorites(self, user_id: str, for_update: bool = False) -> list[str]: ...
    def set_favorite(self, user_id: str, restaurant_id: str, favorite: bool) -> None: ...
    def get_restaurant(self, restaurant_id: str, for_update: bool = False) -> Restaurant | None: ...
    def list_categories(self, restaurant_id: str) -> list[str]: ...
    def list_menu(
        self, restaurant_id: str, category: str | None, limit: int, offset: int
    ) -> list[MenuItem]: ...
    def get_menu_item(self, item_id: str, for_update: bool = False) -> MenuItem | None: ...

    def get_menu_items(self, item_ids: list[str], for_update: bool = False) -> list[MenuItem]: ...


class CartRepository(Protocol):
    def get_for_user(
        self, user_id: str, restaurant_id: str, for_update: bool = False
    ) -> Cart | None: ...
    def list_for_user(self, user_id: str, limit: int = 100, offset: int = 0) -> list[Cart]: ...
    def add(self, cart: Cart) -> None: ...


class OrderRepository(Protocol):
    def add(self, order: FoodOrder) -> None: ...
    def get_owned(self, order_id: str, user_id: str) -> FoodOrder | None: ...
    def get_locked(self, order_id: str) -> FoodOrder | None: ...
    def find_by_provider_order(self, provider_order_id: str) -> FoodOrder | None: ...
    def has_payment_event(self, event_id: str) -> bool: ...
    def add_payment_event(self, event: PaymentEvent) -> None: ...
    def get_by_checkout_key(self, user_id: str, key: str) -> FoodOrder | None: ...
    def list_for_user(self, user_id: str, limit: int, offset: int) -> list[FoodOrder]: ...
    def list_for_restaurant(
        self, restaurant_id: str, limit: int, offset: int
    ) -> list[FoodOrder]: ...


@dataclass(frozen=True)
class PaymentResult:
    provider: str
    status: str
    reference: str
    test_mode: bool = False
    recipient: str | None = None
    recipient_name: str | None = None


class PaymentGateway(Protocol):
    def authorize(self, amount: Decimal, method: str) -> PaymentResult: ...
