"""Repository and reusable service ports shared by customer use cases."""

from typing import Protocol

from app.infrastructure.models import (
    ActionToken,
    Address,
    AuthSession,
    OAuthState,
    OAuthTicket,
    RefreshToken,
    Role,
    SocialAccount,
    User,
)
from app.users.shared.dto.tokens import TokenResponse


class UserRepository(Protocol):
    def get_by_id(self, user_id: str, for_update: bool = False) -> User | None: ...

    def get_by_email(self, email: str) -> User | None: ...

    def add(self, user: User) -> None: ...


class AddressRepository(Protocol):
    def get_owned(
        self, address_id: str, user_id: str, for_update: bool = False
    ) -> Address | None: ...

    def list_for_user(self, user_id: str, for_update: bool = False) -> list[Address]: ...

    def add(self, address: Address) -> None: ...

    def delete(self, address: Address) -> None: ...


class ActionTokenRepository(Protocol):
    def get_customer_role(self) -> Role: ...
    def get_type_id(self, purpose: str) -> int: ...
    def find(
        self, token_hash: str, purpose: str, for_update: bool = False
    ) -> ActionToken | None: ...
    def invalidate(self, user_id: str, purpose: str) -> None: ...
    def add(self, token: ActionToken) -> None: ...


class SessionRepository(Protocol):
    def get(self, session_id: str, for_update: bool = False) -> AuthSession | None: ...
    def add(self, session: AuthSession) -> None: ...
    def add_refresh(self, token: RefreshToken) -> None: ...
    def find_refresh(self, token_hash: str, for_update: bool = False) -> RefreshToken | None: ...
    def revoke_all(self, user_id: str) -> None: ...


class SocialRepository(Protocol):
    def find_account(self, provider: str, subject: str) -> SocialAccount | None: ...
    def add_account(self, account: SocialAccount) -> None: ...
    def add_state(self, state: OAuthState) -> None: ...
    def get_state(self, state_hash: str) -> OAuthState | None: ...
    def add_ticket(self, ticket: OAuthTicket) -> None: ...
    def get_ticket(self, ticket_hash: str, for_update: bool = False) -> OAuthTicket | None: ...


class SessionIssuerInterface(Protocol):
    def create_session(self, user: User) -> TokenResponse: ...
    def issue_token_pair(self, user: User, session: AuthSession) -> TokenResponse: ...


class AccessAuthenticatorInterface(Protocol):
    def authenticate_access(self, raw_token: str) -> User: ...


class EmailActionServiceInterface(Protocol):
    def queue_email_action(self, user: User, purpose: str) -> None: ...
    def require_action(self, raw_token: str, purpose: str) -> tuple[User, ActionToken]: ...
